            </p>
            <h5>Measures like GDP, GNP, NI, and PI:</h5>
            <p>
                <ul>
                    <li><strong>GDP (Gross Domestic Product):</strong> Measures the value of economic production within a country's borders.</li>
                    <li><strong>GNP (Gross National Product):</strong> Includes all production by a country's residents, regardless of location.</li>
                    <li><strong>NI (National Income):</strong> Estimates a country's total earnings, minus depreciation.</li>
                    <li><strong>PI (Personal Income):</strong> The total income received by households.</li>
                </ul>
            </p>
            <h5>Components of National Income:</h5>
            <p>
                National income includes wages, profits, rents, corporate taxes, and owner incomes, all contributing to the production output.
            </p>
            <h5>Uses and Limitations:</h5>
            <p>
                National income data is used for measuring economic growth, comparing living standards, and informing government policy. However, it has limitations such as difficulty in capturing the underground economy, quality of goods, environmental impact, and income distribution changes.
